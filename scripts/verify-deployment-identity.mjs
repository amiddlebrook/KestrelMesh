/** Deployment safety invariant: a repository may deploy only its own Worker and D1 binding. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {join,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=join(dirname(fileURLToPath(import.meta.url)),'..');
const read=(p)=>readFileSync(join(root,p),'utf8');
const cfg=JSON.parse(read('wrangler.jsonc'));
const slug="kestrelmesh";
const app="KestrelMesh";
const expectedRepo=`amiddlebrook/${app}`;
const expectedWorker=`portfolio-${slug}`;
const expectedDb=`${expectedWorker}-db`;
assert.equal(process.env.GITHUB_REPOSITORY||expectedRepo,expectedRepo,'Deployment rejected: GitHub owner/repository mismatch');
assert.equal(cfg.name,expectedWorker,'Deployment rejected: wrong Cloudflare Worker script');
assert.equal(cfg.main,'src/index.ts');
assert.equal(cfg.workers_dev,true,'Deployment route must match the recorded free Workers hostname');
assert.equal(cfg.d1_databases?.length,1,'Deployment must bind exactly one product-specific D1 database');
assert.equal(cfg.d1_databases[0].binding,'DB');
assert.equal(cfg.d1_databases[0].database_name,expectedDb,'Deployment rejected: wrong D1 database name');
assert.equal(cfg.d1_databases[0].migrations_dir,'migrations');
assert.equal(cfg.assets?.directory,'./public');
assert.deepEqual(cfg.assets?.run_worker_first,['/api/*'],'Auth routes must execute in the Worker');
assert.equal(cfg.vars?.FREE_AI_ENABLED,'false','Remote AI must default to disabled');
assert.ok(!cfg.queues&&!cfg.r2_buckets&&!cfg.workflows,'New services require separate quota/security review');
const boot=read('scripts/bootstrap-d1.sh');
assert.ok(boot.includes(`DB_NAME="${expectedDb}"`),'D1 provisioner target differs from Worker config');
const deploy=read('.github/workflows/deploy.yml');
assert.ok(deploy.includes(`https://${expectedWorker}.averymiddlebrook2014.workers.dev`),'Production smoke URL does not match this Worker');
console.log(`${app}: single-application deployment scope verified (${expectedWorker}, ${expectedDb}, ${expectedRepo})`);
